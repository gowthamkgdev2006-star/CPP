#include<iostream>
using namespace std;

int main()
{         //Index 0  1  2  3  4
    int arr[5] = {1, 2, 3, 4, 5};

    // Accessing array elements using index
    cout << "Element at [0]: " << arr[0] << endl;
    cout << "Element at [1]: " << arr[1] << endl;
    cout << "Element at [2]: " << arr[2] << endl;
    cout << "Element at [3]: " << arr[3] << endl;
    cout << "Element at [4]: " << arr[4] << endl;
    
    return 0;
}
