#include<iostream>
using namespace std;

int main()
{         //Index 0  1  2  3  4
    int arr[5] = {1, 2, 3, 4, 5};

    // Accessing array elements using index
    cout << "First element: " << arr[0] << endl;
    cout << "Second element: " << arr[1] << endl;
    cout << "Third element: " << arr[2] << endl;
    cout << "Fourth element: " << arr[3] << endl;
    cout << "Fifth element: " << arr[4] << endl;

    return 0;
}
