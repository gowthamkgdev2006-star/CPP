#include<iostream>
using namespace std;

int main()
{
    int a = 10;

    // Executes only if the condition is true.
    if(a < 5)
    {
        cout << "a is less than 5" << endl;
    }

    // Executes only if the condition is false.
    else
    {
        cout << "a is not less than 5" << endl;
    }
    
    return 0;
}
