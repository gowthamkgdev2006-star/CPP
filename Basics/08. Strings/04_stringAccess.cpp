#include<iostream>
#include<string>
using namespace std;

int main()
{
    string word = "Hello";

    // Accessing individual characters using index
    cout << "First character: " << word[0] << endl;
    cout << "Second character: " << word[1] << endl;
    cout << "Third character: " << word[2] << endl;
    cout << "Fourth character: " << word[3] << endl;
    cout << "Fifth character: " << word[4] << endl;

    return 0;
}
